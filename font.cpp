//================================================
// 字库索引表
//================================================

ChineseFont fontTable[] =
{

    {0x6709, FONT_YOU},       // 有
    {0x7EBF, FONT_XIAN},      // 线
    {0x7535, FONT_DIAN},      // 电
    {0x89C6, FONT_SHI},       // 视

    {0x6D41, FONT_LIU},       // 流
    {0x5A92, FONT_MEI},       // 媒
    {0x4F53, FONT_TI},        // 体

    {0x6570, FONT_SHU},       // 数
    {0x64AD, FONT_BO},        // 播

    {0x5361, FONT_KA},        // 卡
    {0x62C9, FONT_LA},        // 拉

    {0x5173, FONT_GUAN},      // 关
    {0x673A, FONT_JI}         // 机

};


const int fontCount =
sizeof(fontTable)/sizeof(fontTable[0]);




//================================================
// 查找字体
//================================================

const uint8_t *FindFont(uint16_t code)
{

    for(int i=0;i<fontCount;i++)
    {

        if(fontTable[i].unicode == code)
        {
            return fontTable[i].bitmap;
        }

    }

    return nullptr;

}




//================================================
// UTF-8转换Unicode
//================================================

uint16_t UTF8Decode(
    const char *str,
    int &length
)
{

    uint8_t c = str[0];


    if(c < 0x80)
    {

        length = 1;

        return c;

    }
    else if((c & 0xE0)==0xC0)
    {

        length = 2;

        return

        ((str[0]&0x1F)<<6)
        |
        (str[1]&0x3F);

    }
    else
    {

        length = 3;

        return

        ((str[0]&0x0F)<<12)
        |
        ((str[1]&0x3F)<<6)
        |
        (str[2]&0x3F);

    }

}





//================================================
// 绘制16×16中文
//================================================

void DrawChinese16(

    Arduino_GFX *gfx,

    int x,

    int y,

    const char *text,

    uint16_t color

)
{

    while(*text)
    {

        int len;


        uint16_t code =
        UTF8Decode(
            text,
            len
        );


        const uint8_t *font =
        FindFont(code);



        if(font)
        {

            for(int row=0; row<16; row++)
            {

                uint16_t line;


                // ESP32读取PROGMEM

                line =
                ((uint16_t)pgm_read_byte(
                    font + row*2
                ) << 8)
                |
                pgm_read_byte(
                    font + row*2 + 1
                );



                for(int col=0; col<16; col++)
                {

                    if(line & (0x8000 >> col))
                    {

                        gfx->drawPixel(

                            x + col,

                            y + row,

                            color

                        );

                    }

                }

            }

        }


        x += 16;

        text += len;

    }

}




//================================================
// 文字宽度计算
//================================================

int GetMixedWidth(
    const char *text
)
{

    int width=0;


    while(*text)
    {

        if((uint8_t)*text >= 0x80)
        {

            width += 16;

            text += 3;

        }
        else
        {

            width += 8;

            text++;

        }

    }


    return width;

}